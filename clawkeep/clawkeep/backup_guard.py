"""ClawKeep's own boundary around `openclaw backup create`.

`openclaw backup create` is the archiver on the OpenClaw edition and it stays
the authority: its path-traversal, archive-root, symlink and SQLite-integrity
checks are not bypassed, loosened or re-implemented here. What this module owns
is everything ClawKeep does AROUND that call, for the failures field boxes hit
on OpenClaw 2026.9.4:

MANAGED LINKS
  The archiver refuses any symlink whose target lies outside the assets it
  declared ("Archive symbolic link target must be relative", then, for a
  relative one, "… is outside the declared backup assets") — and it refuses
  while WRITING, so the whole run fails. The core skips its own link trees
  only at the canonical state root (`<state>/plugin-skills`, `<state>/npm`,
  a registered plugin's `node_modules`); the same trees anywhere else in the
  backup fail it. On a real box: `plugin-skills/<skill> -> <global
  openclaw>/dist/extensions/…` inside the stray `~/.openclaw/.openclaw` tree
  and inside the Codex harness's own home, the `node_modules/openclaw` peer
  link the plugin installer writes, the Coding Agent's worktree
  `node_modules -> <project>/node_modules`, the legacy `plugin-runtime-deps/`
  cache an older core staged in the state dir. The explicit rule
  (:func:`managed_rule`) — a link the archiver would refuse is OMITTED when it
  is

      * package-manager output: named `node_modules`, below a `node_modules`
        directory, or below a pnpm store (`…/pnpm/store/…`);
      * OpenClaw's own plugin link: in a `plugin-skills` directory, or below
        `<state>/plugin-runtime-deps/`;
      * cache: below a `.cache` directory;
      * a Chromium `SingletonSocket` whose target is gone — the lock of a
        browser that is not running (a LIVE one is left alone: it is how a
        running browser is found).

  Each is regenerated by the tool that wrote it. It is omitted by DETACHING it
  for the length of the archive build — the link's own text is written to a
  journal first, the link is unlinked, and it is put back exactly as it was
  the moment the build ends, succeeded or not. A run killed mid-build (the
  bridge's four-hour cap sends SIGKILL) leaves the journal behind, and the
  next run puts the links back before it does anything else. The link is
  never followed: only its text is read.

  Every OTHER refused link is left exactly where it is and the archiver's
  refusal stands: ClawKeep never carries or follows a link out of the backup.
  The failure is reported as such, naming the link and where it points.

DUPLICATE LOGICAL PATHS
  Two planned assets that would be written to the same archive path — the
  same path, one inside the other, or two names only a case-insensitive
  filesystem tells apart — are refused BEFORE the archiver runs, naming both
  sources. A duplicate the archiver finds itself (while verifying) is mapped
  back to the source it was written from and reported the same way.

FILES THAT VANISH MID-WALK
  An ENOENT on a path inside the backup is a live-write race, not a broken box:
  it is marked transient so `runner` rebuilds the archive (bounded). The same
  sentence about a path OUTSIDE the backup is not a race and is not retried.

SQLITE INTEGRITY
  See :mod:`clawkeep.sqlite_recovery`: index-only damage is rebuilt, with a
  copy kept first, and the archive retried once per database; any other damage
  stops the backup with a sentence saying what it found and that ClawKeep left
  the database untouched.

LEFTOVERS
  On a failed `--verify` the core has already PUBLISHED the archive into the
  output directory, where the runner never learns its name — a plaintext,
  credential-bearing tarball left beside the next run. Whatever a failed call
  leaves in ClawKeep's output directory is removed before the error travels on.
"""

