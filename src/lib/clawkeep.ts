/** Delete a snapshot. Refused (SnapshotLockedError) if it's locked. */
export async function deleteSnapshot(name: string): Promise<void> {
  assertSnapshotName(name);
  const bin = await pairedDaemonBin();
  const resp = await spawnCliJson<MutationResponse>(bin, "delete", [name], { timeoutMs: 60_000 });
  if (!resp.ok) {
    if (resp.kind === "locked") {
      throw new SnapshotLockedError(resp.error ?? "snapshot is locked");
    }
    throw new ClawKeepError(resp.error ?? "delete failed", 502);
  }
}

/** Run retention on demand: keep the newest `keepLast` unlocked snapshots. */
export async function pruneSnapshots(keepLast: number): Promise<string[]> {
  const bin = await pairedDaemonBin();
  const resp = await spawnCliJson<MutationResponse & { deleted?: string[] }>(
    bin,
    "prune",
    ["--keep-last", String(Math.max(0, Math.floor(keepLast)))],
    { timeoutMs: 60_000 },
  );
  if (!resp.ok) {
    throw new ClawKeepError(resp.error ?? "prune failed", 502);
  }
  return resp.deleted ?? [];
}

export async function runRestore(
  name: string,
  opts: { passphrase?: string } = {},
): Promise<RestoreOk> {
  // Restore is destructive — sanity-check the name shape on this side too,
  // not just inside the Python CLI. A hostile input here couldn't escape the
  // prefix (we always concat with the portal-issued prefix on the Python
  // side) but bouncing it early gives the user a clearer error. Accept both
  // the new encrypted form (`.tar.gz.enc`) and the legacy unencrypted one
  // (`.tar.gz`); the daemon detects which is which on its end too.
  assertSnapshotName(name);
  const bin = await pairedDaemonBin();
  await setRestoring(true);
  try {
    const runWith = async (extraArgs: string[]) => {
      const resp = await spawnCliJson<RestoreCliResponse>(
        bin,
        "restore",
        [name, ...extraArgs],
        { timeoutMs: RESTORE_TIMEOUT_MS },
      );
      if (!resp.ok) {
        if (resp.kind === "wrong_password" || resp.kind === "passphrase_missing") {
          throw new RestoreNeedsPassphraseError(resp.error, resp.kind);
        }
        throw new ClawKeepError(resp.error, 502);
      }
      return resp;
    };
    // Stage a one-shot passphrase tmpfile when the caller supplied one, so
    // the password is fed via `--passphrase-file` rather than ever entering
    // argv (which would expose it in /proc/<pid>/cmdline).
    if (opts.passphrase) {
      return await withSecretTmpfile(opts.passphrase, (tmpFile) =>
        runWith(["--passphrase-file", tmpFile]),
      );
    }
    return await runWith([]);
  } finally {
    await setRestoring(false).catch(() => { /* best-effort cleanup */ });
  }
}

export async function runBackup(
  opts: { idle?: boolean; label?: string } = {},
): Promise<BackupResult> {
  const bin = await pairedDaemonBin();
  return new Promise((resolve) => {
    const env = buildSpawnEnv();
    const args = ["--config", CLAWKEEP_CONFIG_PATH];
    if (opts.idle) args.push("--idle");
    // Optional snapshot label from the UI's "Name this backup" field. Passed
    // as an argv pair (not a secret, unlike the passphrase) — the daemon
    // records it in the manifest after a successful upload.
    const label = opts.label?.trim();
    if (label) args.push("--label", label);
    const child = spawn(bin, args, { env, stdio: ["ignore", "pipe", "pipe"] });
    let stdout = "";
    let stderr = "";
    let settled = false;
    const settle = (result: BackupResult) => {
      if (settled) return;
      settled = true;
      clearTimeout(killTimer);
      resolve(result);
    };
    // Mirror spawnCliJson's kill-timer: SIGKILL a hung daemon and resolve
    // with a non-zero exit so the caller surfaces "backup timed out" rather
    // than leaking a worker forever.
    const killTimer = setTimeout(() => {
      try { child.kill("SIGKILL"); } catch { /* already gone */ }
      settle({ exitCode: 124, stdout, stderr: appendCapped(stderr, "\nbackup timed out") });
    }, BACKUP_TIMEOUT_MS);
    child.stdout.on("data", (b: Buffer) => {
      stdout = appendCapped(stdout, b.toString("utf8"));
    });
    child.stderr.on("data", (b: Buffer) => {
      stderr = appendCapped(stderr, b.toString("utf8"));
    });
    child.on("error", (e) => {
      // ENOENT etc. — synthesize a non-zero exit so callers can surface it.
      settle({ exitCode: 127, stdout, stderr: appendCapped(stderr, e.message) });
    });
    child.on("close", (code) => {
      settle({ exitCode: code ?? -1, stdout, stderr });
    });
  });
}
