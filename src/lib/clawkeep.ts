const RESTORE_TIMEOUT_MS = 30 * 60 * 1000; // hard cap matches openclaw verify + multipart download
// Generous cap for a full backup (openclaw backup create + multipart upload).
// A hung clawkeepd must not hold a Next.js worker open forever.
const BACKUP_TIMEOUT_MS = 60 * 60 * 1000;

function spawnCliJson<T>(
  bin: string,
  subcommand: string,
  extraArgs: string[],
  opts: { timeoutMs: number },
): Promise<T> {
  const { timeoutMs } = opts;
  return new Promise((resolve, reject) => {
    const env = buildSpawnEnv();

    // The real `clawkeep` script lives next to clawkeepd. If we resolved
    // clawkeepd to ~/.local/bin/clawkeepd, derive the sibling `clawkeep`
    // binary path; the system PATH version may not exist.
    const clawkeepBin = bin.endsWith("clawkeepd")
      ? bin.replace(/clawkeepd$/, "clawkeep")
      : "clawkeep";

    // `--config` is a per-subcommand flag in cli.py — order is
    // `clawkeep <subcommand> [<positional>] --config <path>`.
    const args = [subcommand, ...extraArgs, "--config", CLAWKEEP_CONFIG_PATH];
    const child = spawn(clawkeepBin, args, { env, stdio: ["ignore", "pipe", "pipe"] });

    let stdout = "";
    let stderr = "";
    // Decode through a StringDecoder so a multibyte UTF-8 sequence split across
    // two 'data' events (e.g. a Cyrillic snapshot label straddling a chunk
    // boundary) isn't corrupted into U+FFFD — the decoder buffers the partial
    // trailing bytes until the next chunk (flushed via .end() on close).
    const outDecoder = new StringDecoder("utf8");
    const errDecoder = new StringDecoder("utf8");
    const killTimer = setTimeout(() => {
      try { child.kill("SIGKILL"); } catch { /* already gone */ }
    }, timeoutMs);

    child.stdout.on("data", (b: Buffer) => {
      stdout = appendCapped(stdout, outDecoder.write(b));
    });
    child.stderr.on("data", (b: Buffer) => {
      stderr = appendCapped(stderr, errDecoder.write(b));
    });
    child.on("error", (err) => {
      clearTimeout(killTimer);
      // An unresolved binary (clawkeep/clawkeepd not on PATH or the derived
      // sibling missing) surfaces as ENOENT. Turn it into a friendly 503
      // instead of a raw "spawn ... ENOENT" 500.
      if ((err as NodeJS.ErrnoException).code === "ENOENT") {
        reject(new ClawKeepError("ClawKeep daemon not installed", 503));
        return;
      }
      reject(new Error(`spawn ${clawkeepBin} failed: ${err.message}`));
    });
    child.on("close", (code) => {
      clearTimeout(killTimer);
      // Flush any bytes the decoder is still holding (a trailing partial
      // multibyte sequence) before parsing.
      stdout = appendCapped(stdout, outDecoder.end());
      stderr = appendCapped(stderr, errDecoder.end());
      // Both `clawkeep snapshots` and `clawkeep restore` print a single JSON
      // object on stdout — even on errors. Parse first; fall back to stderr
      // text if parsing fails so the caller still gets a usable message.
      try {
        const parsed = JSON.parse(stdout.trim().split("\n").pop() || "{}") as T;
        resolve(parsed);
      } catch {
        reject(
          new Error(
            `clawkeep ${subcommand} exited ${code ?? "?"}; ` +
              `non-JSON output. stderr=${stderr.slice(-500)}`,
          ),
        );
      }
    });
  });
}

async function fetchCloudSnapshots(): Promise<SnapshotsResponse> {
  // Fail fast + friendly on the unpaired case rather than shelling out and
  // surfacing the daemon's raw "no token" error as a 502.
  const bin = await pairedDaemonBin();
  const resp = await spawnCliJson<SnapshotsResponse>(bin, "snapshots", [], { timeoutMs: 60_000 });
  if (!resp.ok) {
    throw mapSnapshotsError(resp);
  }
  return resp;
}

export async function listCloudSnapshots(): Promise<CloudSnapshot[]> {
  return (await fetchCloudSnapshots()).snapshots ?? [];
}

/**
 * Seed state.json from the account's existing cloud snapshots.
 *
 * The dashboard's "last backup / cloud size / snapshot count" all come from
 * state.json, which is only written by a *local* backup run. So right after
 * (re)pairing an account that already has backups in the cloud, the device
 * has no local record of them and would show "0 B / 0 / never" until the next
 * backup. Pulling the real snapshot list on pair fixes that — the dashboard
 * reflects what's actually in the account's cloud prefix immediately.
 *
 * Best-effort: a cloud-list failure (offline, portal hiccup, daemon missing)
 * leaves state.json untouched rather than blocking the pair. Combined with the
 * account-change `unpairLocal({ clearStats })` wipe, an offline re-pair then
 * shows a clean slate instead of the previous account's numbers.
 */
export async function syncStateFromCloud(): Promise<void> {
  let resp: SnapshotsResponse;
  try {
    resp = await fetchCloudSnapshots();
  } catch (err) {
    console.warn("[clawkeep] cloud snapshot sync after pair failed (continuing):", err);
    return;
  }
  const snapshots = resp.snapshots ?? [];
  const lastBackupAtMs = snapshots.reduce((max, s) => Math.max(max, s.last_modified_ms ?? 0), 0);
  // Prefer the daemon's authoritative prefix total; fall back to summing the
  // per-snapshot sizes only if an older daemon doesn't report cloudBytes.
  const cloudBytes = resp.cloudBytes ?? snapshots.reduce((sum, s) => sum + (s.size_bytes ?? 0), 0);
  await writeStateFile({
    last_backup_at_ms: lastBackupAtMs,
    last_cloud_bytes: cloudBytes,
    last_snapshot_count: snapshots.length,
    last_heartbeat_at_ms: lastBackupAtMs,
    last_heartbeat_status: "",
    last_step: "",
    last_step_at_ms: 0,
    upload_bytes_total: 0,
    upload_bytes_done: 0,
    upload_started_at_ms: 0,
  });
}

