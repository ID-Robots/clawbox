// Cap stdout/stderr capture so a chatty `openclaw backup create` over a
// large workspace can't OOM the Next.js process. We only show a 2 KB tail
// in the UI anyway, so keeping a generous tail buffer (64 KB) leaves plenty
// of room for the final summary line + any stderr trace while staying
// bounded.
const MAX_OUTPUT_BYTES = 64 * 1024;

function appendCapped(prev: string, chunk: string): string {
  const next = prev + chunk;
  if (next.length <= MAX_OUTPUT_BYTES) return next;
  return next.slice(next.length - MAX_OUTPUT_BYTES);
}

export interface CloudSnapshot {
  name: string;
  size_bytes: number;
  last_modified_ms: number;
  /** Human label from the sidecar manifest; null/undefined = unnamed. */
  label?: string | null;
  /** Protected flag — a locked snapshot can't be deleted (manual or auto). */
  locked?: boolean;
}

interface SnapshotsResponse {
  ok: boolean;
  error?: string;
  /** Coarse failure classification from the daemon so we can map to a
   * sensible HTTP status instead of collapsing everything into 502. */
  kind?: string;
  snapshots?: CloudSnapshot[];
  quotaBytes?: number;
  cloudBytes?: number;
}

/**
 * Map a failed `snapshots` daemon response to an HTTP status + a friendly
 * message. We deliberately never surface `resp.error` verbatim — it can be a
 * raw Python traceback or leak internal paths — so the caller gets a clean,
 * classified error the UI can act on.
 */
function mapSnapshotsError(resp: SnapshotsResponse): ClawKeepError {
  switch (resp.kind) {
    case "unpaired":
    case "no_token":
    case "not_paired":
      // Same answer as the pre-flight check, IF the daemon ever says so: today
      // `clawkeep snapshots` classifies nothing — `cli.py::_emit_err` prints
      // `{"ok":false,"error":…}` with no `kind` for `TokenError` too, so these
      // cases are unreached and the token vanishing mid-session still falls to
      // `default:` (502). Kept as the mapping to use when the daemon starts
      // classifying its errors — which needs a `no_token` kind that
      // `api.ApiError` does not have either (its union is auth | quota_full |
      // tier | server | network | other), so making this branch live is a
      // daemon-side change, not just a wiring one.
      return new ClawKeepNotPairedError();
    case "auth":
    case "unauthorized":
    case "revoked":
    case "forbidden":
      return new ClawKeepError(
        "ClawKeep authorisation was rejected — re-pair the device",
        401,
      );
    case "network":
    case "offline":
    case "timeout":
      return new ClawKeepError("Could not reach the ClawKeep portal", 504);
    case "portal":
    case "server":
      return new ClawKeepError("The ClawKeep portal returned an error", 502);
    default:
      // Covers missing-dependency (e.g. boto3) and any unclassified daemon
      // failure without leaking the raw internal string.
      return new ClawKeepError("Could not list cloud backups", 502);
  }
}

interface RestoreOk {
  ok: true;
  archive: string;
  archiveBytes: number;
  /** Members the daemon deliberately did not recreate — unsafe absolute
   *  symlinks. Normally empty; when it is not, the restore is INCOMPLETE and
   *  the UI has to say so rather than showing a clean success. Optional
   *  because a daemon predating the field simply omits it. */
  skippedMembers?: string[];
  assets: { kind: string; targetPath: string; backupPath: string; bytesRestored: number }[];
}

interface RestoreErr {
  ok: false;
  error: string;
  /** Distinct error kinds the daemon emits so the UI can react with the
   * right modal — otherwise `error: "..."` is opaque. */
  kind?: "wrong_password" | "passphrase_missing";
}

type RestoreCliResponse = RestoreOk | RestoreErr;

